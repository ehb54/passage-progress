#!/usr/bin/env python3
"""Build the distributables from the extension sources.

    python3 tools/build.py

Produces
  docs/index.html                       install page (GitHub Pages), with the
                                        bookmarklet link baked in
  docs/privacy.html                     privacy policy (for the Chrome Web Store)
  docs/passage-progress-bookmarklet.js  readable source of the bookmarklet
  docs/icon128.png
  dist/passage-progress-<version>.zip   Chrome Web Store upload

Re-run after changing content.js, and commit the docs/ output.
"""
import json
import os
import re
import shutil
import urllib.parse
import zipfile

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

# Fill in once the Chrome Web Store listing is live (unlisted is fine).
STORE_URL = ""

EXTENSION_FILES = [
    "manifest.json",
    "background.js",
    "content.js",
    "icons/icon16.png",
    "icons/icon32.png",
    "icons/icon48.png",
    "icons/icon128.png",
]


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def bookmarklet_source(version):
    shim = read("bookmarklet/shim.js")
    content = read("content.js")
    return (
        f"// Passage Progress {version}, bookmarklet build. Generated by tools/build.py\n"
        "// from bookmarklet/shim.js + content.js; https://github.com/ehb54/passage-progress\n"
        "(() => {\n"
        "const PP_MODE = 'bookmarklet';\n"
        "const prev = window.__passageProgress;\n"
        "// clicked again on the same page: show/hide\n"
        "if (prev && prev.alive && prev.alive()) { if (prev.toggle) prev.toggle(); return; }\n"
        "// the browser extension is already running here\n"
        "if (!prev && document.getElementById('passage-progress-host')) {\n"
        "  alert('Passage Progress is already running on this page (browser extension).');\n"
        "  return;\n"
        "}\n"
        f"{shim}\n{content}\n"
        "})();\n"
    )


def light_minify(src):
    """Drop blank lines, whole-line // comments and indentation.

    Line breaks are kept, so automatic semicolon insertion and trailing
    comments behave exactly as in the source.
    """
    out = []
    for line in src.split("\n"):
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        out.append(s)
    return "\n".join(out)


def bookmarklet_href(src):
    code = light_minify(src)
    # Percent-encode everything that could break a URL or an HTML attribute
    # (%, #, &, ", whitespace, backslash, backtick); keep common JS punctuation
    # readable to keep the link short.
    return "javascript:" + urllib.parse.quote(code, safe="!*'();:@=+$,/?[]{}<>|^~-_.")


def apply_store_blocks(html):
    keep, drop = ("STORE", "NOSTORE") if STORE_URL else ("NOSTORE", "STORE")
    html = re.sub(rf"<!--{drop}-->.*?<!--/{drop}-->", "", html, flags=re.S)
    html = html.replace(f"<!--{keep}-->", "").replace(f"<!--/{keep}-->", "")
    return html


def main():
    manifest = json.loads(read("manifest.json"))
    version = manifest["version"]

    src = bookmarklet_source(version)
    write("docs/passage-progress-bookmarklet.js", src)
    href = bookmarklet_href(src)
    if '"' in href or "&" in href:
        raise SystemExit("bookmarklet href contains characters unsafe in an HTML attribute")

    page = read("site/index.html")
    page = apply_store_blocks(page)
    page = (
        page.replace("{{BOOKMARKLET_HREF}}", href)
        .replace("{{STORE_URL}}", STORE_URL)
        .replace("{{VERSION}}", version)
    )
    if "{{" in page:
        raise SystemExit("unfilled placeholder in site/index.html")
    write("docs/index.html", page)
    write("docs/privacy.html", read("site/privacy.html"))
    shutil.copyfile(os.path.join(ROOT, "icons/icon128.png"), os.path.join(ROOT, "docs/icon128.png"))

    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
    zpath = os.path.join(ROOT, "dist", f"passage-progress-{version}.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for rel in EXTENSION_FILES:
            z.write(os.path.join(ROOT, rel), rel)

    print(f"version {version}")
    print(f"bookmarklet link: {len(href) / 1024:.1f} KB")
    print(f"wrote docs/index.html, docs/privacy.html, docs/passage-progress-bookmarklet.js")
    print(f"wrote {os.path.relpath(zpath, ROOT)} ({os.path.getsize(zpath) / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
